import { useState } from "react";
import { emptyTestCaseDraft, inputKindOf, type TestCaseDraft, type TestInputKind } from "../../model/test-cases";
import { errorMessageOf, fieldErrorOf } from "../../model/form-error";
import Button from "../primitives/Button";
import Callout from "../primitives/Callout";
import Checkbox from "../primitives/Checkbox";
import FormField from "../primitives/FormField";
import { RadioOption, Select, TextArea, TextInput } from "../primitives/FormControls";
import Grid from "../primitives/Grid";
import Modal from "../primitives/Modal";
import Stack from "../primitives/Stack";
import { focusFirstProblem } from "../primitives/focus-field";
import JsonAttachment from "./JsonAttachment";
import { describeJsonProblem } from "./json-input";
import type { TestStep } from "./TestCasesView";

interface Props {
  open: boolean;
  onClose: () => void;
  /** Saves it; resolves once saved (the modal closes itself), or rejects with why not. */
  onSubmit: (draft: TestCaseDraft) => Promise<void>;
  /** The test being edited; left out for a new one. */
  initial?: TestCaseDraft;
  /** The name a new one starts with, e.g. one no other test has. */
  defaultName?: string;
  /** The workflow's steps, in the order they run, for where the test starts and stops. */
  steps: TestStep[];
  /** The project's saved dataclips, any of which the test can run with instead of a generated input. */
  dataclips: { id: string; name: string }[];
}

/**
 * A workflow's test case, new or edited: its scenario's name, what goes in
 * and what should come out, where in the workflow it starts and stops, and
 * how it's checked. The input is generated by the assistant from its
 * description, a saved dataclip, or JSON attached to the test (pasted or
 * uploaded). The output is judged by the assistant against its description,
 * compared with an expected output attached as JSON, checked by
 * deterministic tests, or any of them.
 */
export default function TestCaseFormModal({ open, ...rest }: Props) {
  // Mounting the form only while open means its state resets on each open.
  if (!open) return null;
  return <TestCaseForm {...rest} />;
}

function TestCaseForm({ onClose, onSubmit, initial, defaultName = "", steps, dataclips }: Omit<Props, "open">) {
  const [draft, setDraft] = useState<TestCaseDraft>(initial ?? { ...emptyTestCaseDraft, name: defaultName });
  // Switching where the input comes from, or turning the comparison off, keeps what was there until it's saved.
  const [source, setSource] = useState<TestInputKind>(initial ? inputKindOf(initial) : "generated");
  const [compare, setCompare] = useState(Boolean(initial?.expectedOutput?.trim()));
  const [checked, setChecked] = useState(false);
  const [saving, setSaving] = useState(false);
  const [refusal, setRefusal] = useState<unknown>();
  const set = (patch: Partial<TestCaseDraft>) => setDraft((d) => ({ ...d, ...patch }));

  const attachedProblem = (json: string | undefined, missing: string) => (json?.trim() ? (describeJsonProblem(json) ?? undefined) : missing);
  const problems = {
    name: draft.name.trim() ? undefined : "Enter a name for the scenario",
    dataclipId: source === "dataclip" && !draft.dataclipId ? "Pick a saved dataclip" : undefined,
    inputBody: source === "attached" ? attachedProblem(draft.inputBody, "Paste the input, or upload a .json file") : undefined,
    inputDescription: source === "generated" && !draft.inputDescription.trim() ? "Say what goes in" : undefined,
    outputDescription: draft.judge && !draft.outputDescription.trim() ? "Say what should come out, for the assistant to judge against" : undefined,
    expectedOutput: compare ? attachedProblem(draft.expectedOutput, "Paste the expected output, or upload a .json file") : undefined,
    assertions:
      !draft.judge && !compare && !draft.assertions?.trim()
        ? "Write deterministic tests, compare with an expected output, or let the assistant judge the output"
        : undefined,
  };

  async function submit() {
    if (saving) return;
    setChecked(true);
    const missing = focusFirstProblem([
      ["test-name", problems.name],
      ["test-dataclip", problems.dataclipId],
      ["test-input-body", problems.inputBody],
      ["test-input-description", problems.inputDescription],
      ["test-output-description", problems.outputDescription],
      ["test-expected-output", problems.expectedOutput],
      ["test-assertions", problems.assertions],
    ]);
    if (missing) return;
    setSaving(true);
    setRefusal(undefined);
    try {
      await onSubmit({
        ...draft,
        dataclipId: source === "dataclip" ? draft.dataclipId : undefined,
        inputBody: source === "attached" ? draft.inputBody : undefined,
        expectedOutput: compare ? draft.expectedOutput : undefined,
      });
      onClose();
    } catch (error) {
      setRefusal(error);
      setSaving(false);
    }
  }

  const error = (field: keyof typeof problems, apiField: string) => (checked ? problems[field] : undefined) ?? fieldErrorOf(refusal, apiField);
  const errors = {
    name: error("name", "name"),
    dataclipId: error("dataclipId", "dataclip_id"),
    inputBody: error("inputBody", "input_body"),
    inputDescription: error("inputDescription", "input_description"),
    outputDescription: error("outputDescription", "output_description"),
    expectedOutput: error("expectedOutput", "expected_output"),
    assertions: error("assertions", "assertions"),
    start: fieldErrorOf(refusal, "start_job_id"),
    end: fieldErrorOf(refusal, "end_job_id"),
  };
  const shownElsewhere = Object.values(errors).some(Boolean);
  const stepOptions = steps.map((s) => ({ value: s.id, label: s.label }));

  return (
    <Modal
      open
      title={initial ? `Edit ${initial.name}` : "New test case"}
      onClose={onClose}
      widthClass="max-w-2xl"
      footer={
        <>
          <Button variant="secondary" onClick={onClose}>
            Cancel
          </Button>
          <Button onClick={() => void submit()} aria-disabled={saving}>
            {saving ? "Saving…" : initial ? "Save test case" : "Add test case"}
          </Button>
        </>
      }
    >
      <form
        aria-label={initial ? `Edit ${initial.name}` : "New test case"}
        onSubmit={(e) => {
          e.preventDefault();
          void submit();
        }}
      >
        <Stack gap="lg">
          {refusal !== undefined && !shownElsewhere && <Callout variant="danger" role="alert" title={errorMessageOf(refusal)} />}
          <FormField label="Scenario name" htmlFor="test-name" error={errors.name} required>
            <TextInput
              id="test-name"
              autoFocus
              value={draft.name}
              placeholder="Existing citizen is told their ID"
              onChange={(e) => set({ name: e.target.value })}
            />
          </FormField>

          <FormField label="Input">
            <Stack gap="sm">
              <RadioOption
                name="test-input"
                label="Generate from a description"
                hint="The assistant writes an input to match what you describe, each time the test runs."
                checked={source === "generated"}
                onChange={() => setSource("generated")}
              />
              <RadioOption
                name="test-input"
                label="Use a saved dataclip"
                hint={dataclips.length === 0 ? "Save a dataclip first to run with it." : "One of the project's saved dataclips, run as it is."}
                checked={source === "dataclip"}
                disabled={dataclips.length === 0}
                onChange={() => setSource("dataclip")}
              />
              <RadioOption
                name="test-input"
                label="Attach an input"
                hint="Paste JSON or upload a .json file. It's saved with the test and run as it is."
                checked={source === "attached"}
                onChange={() => setSource("attached")}
              />
            </Stack>
          </FormField>
          {source === "dataclip" && (
            <FormField label="Saved dataclip" htmlFor="test-dataclip" error={errors.dataclipId} required>
              <Select
                id="test-dataclip"
                fullWidth
                placeholder="Pick a dataclip"
                value={draft.dataclipId ?? ""}
                options={dataclips.map((d) => ({ value: d.id, label: d.name }))}
                onChange={(e) => set({ dataclipId: e.target.value || undefined })}
              />
            </FormField>
          )}
          {source === "attached" && (
            <FormField label="Attached input" htmlFor="test-input-body" error={errors.inputBody} hint="A JSON object: what the start step receives." required>
              <JsonAttachment
                id="test-input-body"
                value={draft.inputBody ?? ""}
                placeholder={'{\n  "given_name": "Amara",\n  "family_name": "Okafor"\n}'}
                onChange={(inputBody) => set({ inputBody })}
              />
            </FormField>
          )}
          <FormField
            label="Input description"
            htmlFor="test-input-description"
            error={errors.inputDescription}
            required={source === "generated"}
            optional={source !== "generated"}
            hint={source === "generated" ? undefined : `What the ${source === "dataclip" ? "dataclip" : "input"} stands for, for whoever reads the test.`}
          >
            <TextArea
              id="test-input-description"
              rows={2}
              value={draft.inputDescription}
              placeholder="An applicant already registered in Identity, with the same name and date of birth."
              onChange={(e) => set({ inputDescription: e.target.value })}
            />
          </FormField>

          <FormField
            label="Output description"
            htmlFor="test-output-description"
            error={errors.outputDescription}
            required={draft.judge}
            optional={!draft.judge}
            hint={draft.judge ? undefined : "What should happen, for whoever reads the test."}
          >
            <TextArea
              id="test-output-description"
              rows={2}
              value={draft.outputDescription}
              placeholder="The applicant is told their existing national ID, and no new citizen is created."
              onChange={(e) => set({ outputDescription: e.target.value })}
            />
          </FormField>

          <Grid columns={2} gap="md">
            <FormField label="Start step" htmlFor="test-start" error={errors.start}>
              <Select
                id="test-start"
                fullWidth
                value={draft.startStepId ?? ""}
                options={[{ value: "", label: "First step" }, ...stepOptions]}
                onChange={(e) => set({ startStepId: e.target.value || undefined })}
              />
            </FormField>
            <FormField label="End step" htmlFor="test-end" error={errors.end}>
              <Select
                id="test-end"
                fullWidth
                value={draft.endStepId ?? ""}
                options={[{ value: "", label: "Final output" }, ...stepOptions]}
                onChange={(e) => set({ endStepId: e.target.value || undefined })}
              />
            </FormField>
          </Grid>

          <Checkbox
            id="test-judge"
            checked={draft.judge}
            onChange={(judge) => set({ judge })}
            label="Let the assistant judge the output"
            hint="It reads what came out and says whether it matches the output description."
          />
          <Checkbox
            id="test-compare"
            checked={compare}
            onChange={setCompare}
            label="Compare with an expected output"
            hint="Attach the state it should end with. Every key in it must come out with the same value; others can come out too."
          />
          {compare && (
            <FormField label="Expected output" htmlFor="test-expected-output" error={errors.expectedOutput} hint="A JSON object, compared with the state at the end step." required>
              <JsonAttachment
                id="test-expected-output"
                value={draft.expectedOutput ?? ""}
                placeholder={'{\n  "notified": true\n}'}
                onChange={(expectedOutput) => set({ expectedOutput })}
              />
            </FormField>
          )}
          <FormField
            label="Deterministic tests"
            htmlFor="test-assertions"
            error={errors.assertions}
            optional={draft.judge || compare}
            hint="Run against the state at the end step, e.g. expect(state.notified).toBe(true);"
          >
            <TextArea
              id="test-assertions"
              rows={4}
              mono
              spellCheck={false}
              value={draft.assertions ?? ""}
              onChange={(e) => set({ assertions: e.target.value })}
            />
          </FormField>
        </Stack>
      </form>
    </Modal>
  );
}
